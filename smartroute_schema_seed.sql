CREATE VIEW v_route_summary AS
SELECT r.id AS route_id, r.name AS route_name,
       (SELECT COUNT(*) FROM route_stops rs WHERE rs.route_id = r.id) AS stops,
       COUNT(b.id)                      AS buses,
       COALESCE(SUM(b.capacity), 0)     AS total_seats
FROM routes r
LEFT JOIN bus_routes br ON br.route_id = r.id
LEFT JOIN buses b       ON b.id = br.bus_id
GROUP BY r.id;
